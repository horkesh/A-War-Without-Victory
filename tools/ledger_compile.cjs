#!/usr/bin/env node
/**
 * Compile per-PR ledger fragments into docs/PROJECT_LEDGER.md.
 *
 * Why: every PR used to add its entry at the top of the ledger, so any two PRs merging close
 * together conflicted on the same line. Each PR now adds ONE file instead,
 * docs/ledger/fragments/YYYY-MM-DD-<slug>.md. Different files never conflict. This tool stitches
 * all fragments into one generated block of the ledger, newest first.
 *
 * Deterministic: fragments are ordered by date (newest first), then file name (strictCompare,
 * ascending). No clock, no randomness. Running it twice changes nothing.
 *
 * The generated block sits between the BEGIN and END markers, just below the archive-pointer
 * comment. Entries written by hand before fragments existed stay below it, untouched. Never edit
 * inside the markers: edit the fragment and recompile.
 *
 * Usage:
 *   node tools/ledger_compile.cjs            rewrite the generated block
 *   node tools/ledger_compile.cjs --validate check fragment names and headings only
 *   node tools/ledger_compile.cjs --check    validate, and exit 1 if the generated block is stale
 *   --dir <path> --ledger <path>             override locations (tests)
 */
'use strict';

const fs = require('node:fs');
const path = require('node:path');

const BEGIN = '<!-- LEDGER FRAGMENTS:BEGIN (generated by tools/ledger_compile.cjs; edit the fragments, not this block) -->';
const END = '<!-- LEDGER FRAGMENTS:END -->';
const FILE_RE = /^(\d{4}-\d{2}-\d{2})-([a-z0-9][a-z0-9-]*)\.md$/;
const HEADING_RE = /^## (\d{4}-\d{2}-\d{2}) (?:—|-) \S/;

function strictCompare(a, b) {
  return a < b ? -1 : a > b ? 1 : 0;
}

function repoRoot() {
  return path.resolve(__dirname, '..');
}

/** Returns { fragments, errors }. A fragment is { file, date, text }. */
function loadFragments(dir) {
  const errors = [];
  const fragments = [];
  if (!fs.existsSync(dir)) return { fragments, errors };
  const names = fs.readdirSync(dir).filter((n) => n.endsWith('.md') && n !== 'README.md').sort(strictCompare);
  for (const name of names) {
    const match = FILE_RE.exec(name);
    if (!match) {
      errors.push(`${name}: file name must be YYYY-MM-DD-<slug>.md (lowercase letters, digits, hyphens)`);
      continue;
    }
    const text = fs.readFileSync(path.join(dir, name), 'utf8').replace(/\r\n/g, '\n').trim();
    const firstLine = text.split('\n', 1)[0];
    const heading = HEADING_RE.exec(firstLine);
    if (!heading) {
      errors.push(`${name}: first line must be "## YYYY-MM-DD — <title>"`);
      continue;
    }
    if (heading[1] !== match[1]) {
      errors.push(`${name}: heading date ${heading[1]} does not match the file name date ${match[1]}`);
      continue;
    }
    if (text.split('\n').some((line) => line === BEGIN || line === END)) {
      errors.push(`${name}: must not contain the generated-block markers`);
      continue;
    }
    fragments.push({ file: name, date: match[1], text });
  }
  return { fragments, errors };
}

function renderBlock(fragments) {
  const ordered = [...fragments].sort((a, b) => strictCompare(b.date, a.date) || strictCompare(a.file, b.file));
  const body = ordered.map((f) => f.text).join('\n\n');
  return `${BEGIN}\n\n${body}\n\n${END}`;
}

/** Replaces the generated block, or inserts it below the archive-pointer comment. */
function applyBlock(ledgerText, block) {
  const text = ledgerText.replace(/\r\n/g, '\n');
  const begin = text.indexOf(BEGIN);
  const end = text.indexOf(END);
  if (begin !== -1 && end !== -1 && end > begin) {
    return text.slice(0, begin) + block + text.slice(end + END.length);
  }
  if (begin !== -1 || end !== -1) {
    throw new Error('ledger has only one of the two generated-block markers');
  }
  const closeComment = text.indexOf('\n-->\n');
  if (closeComment === -1) throw new Error('ledger has no archive-pointer comment to insert below');
  const at = closeComment + '\n-->\n'.length;
  return `${text.slice(0, at)}\n${block}\n${text.slice(at)}`;
}

function main(argv) {
  const args = argv.slice(2);
  const opt = (name) => {
    const i = args.indexOf(name);
    return i === -1 ? null : args[i + 1];
  };
  const root = repoRoot();
  const dir = opt('--dir') || path.join(root, 'docs', 'ledger', 'fragments');
  const ledgerPath = opt('--ledger') || path.join(root, 'docs', 'PROJECT_LEDGER.md');
  const validateOnly = args.includes('--validate');
  const check = args.includes('--check');

  const { fragments, errors } = loadFragments(dir);
  if (errors.length > 0) {
    for (const e of errors) console.error(`ledger fragment error: ${e}`);
    return 1;
  }
  if (validateOnly) {
    console.log(`ledger fragments: ${fragments.length} valid`);
    return 0;
  }

  const current = fs.readFileSync(ledgerPath, 'utf8');
  const next = applyBlock(current, renderBlock(fragments));
  if (check) {
    if (next !== current.replace(/\r\n/g, '\n')) {
      console.error('ledger generated block is stale: run `node tools/ledger_compile.cjs`');
      return 1;
    }
    console.log(`ledger fragments: ${fragments.length} valid, block current`);
    return 0;
  }
  if (next !== current) fs.writeFileSync(ledgerPath, next, 'utf8');
  console.log(`ledger fragments: ${fragments.length} compiled into ${path.relative(root, ledgerPath)}`);
  return 0;
}

if (require.main === module) {
  process.exit(main(process.argv));
}

module.exports = { BEGIN, END, FILE_RE, HEADING_RE, loadFragments, renderBlock, applyBlock, strictCompare, main };
