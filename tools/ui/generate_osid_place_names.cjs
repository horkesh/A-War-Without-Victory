#!/usr/bin/env node
/**
 * Generates src/ui/shared/osidPlaceNames.generated.ts from the operational settlements GeoJSON.
 *
 * Why: several player-facing surfaces (sitrep fronts, operation proposals, supply evidence)
 * render an OSID before the GeoJSON name map has loaded, or in shared code that never sees it,
 * and fell back to humanizing the ASCII slug ("Arapusa (bosanska krupa)"). The generated table
 * gives every OSID its census spelling synchronously. Display-only; OSIDs stay ASCII keys.
 *
 * Deterministic: OSIDs sorted with a plain code-unit compare; no timestamps.
 * Usage: node tools/ui/generate_osid_place_names.cjs [--check]
 */
const fs = require('fs');
const path = require('path');

const repo = path.resolve(__dirname, '..', '..');
const sourcePath = path.join(repo, 'data', 'derived', 'operational', 'operational_settlements.geojson');
const outPath = path.join(repo, 'src', 'ui', 'shared', 'osidPlaceNames.generated.ts');

function build() {
  const geojson = JSON.parse(fs.readFileSync(sourcePath, 'utf8'));
  const rows = new Map();
  for (const feature of geojson.features ?? []) {
    const props = feature?.properties ?? {};
    const osid = props.osid;
    if (typeof osid !== 'string' || !osid) continue;
    const settlement = String(props.settlement_name ?? '').replace(/\s*\(\+\d+\)\s*$/, '').trim();
    const municipality = String(props.mun1990_name ?? '').trim();
    if (!settlement) throw new Error(`OSID without settlement_name: ${osid}`);
    if (rows.has(osid)) throw new Error(`Duplicate OSID in GeoJSON: ${osid}`);
    rows.set(osid, [settlement, municipality]);
  }
  const osids = [...rows.keys()].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
  const lines = osids.map((osid) => `  ${JSON.stringify(osid)}: ${JSON.stringify(rows.get(osid))},`);
  return [
    '// GENERATED by tools/ui/generate_osid_place_names.cjs from',
    '// data/derived/operational/operational_settlements.geojson. Do not edit by hand.',
    '// OSID -> [settlement name, municipality name], census spelling. Display-only.',
    'export const OSID_PLACE_NAMES: Readonly<Record<string, readonly [string, string]>> = {',
    ...lines,
    '};',
    '',
  ].join('\n');
}

const output = build();
if (process.argv.includes('--check')) {
  const current = fs.existsSync(outPath) ? fs.readFileSync(outPath, 'utf8') : '';
  if (current !== output) {
    console.error(`${path.relative(repo, outPath)} is stale; run node tools/ui/generate_osid_place_names.cjs`);
    process.exit(1);
  }
  console.log('osid place names up to date');
} else {
  fs.writeFileSync(outPath, output);
  console.log(`wrote ${path.relative(repo, outPath)}`);
}
