import { spawn } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve, join } from 'node:path';
const logs = import.meta.dirname;
const case3 = process.argv.includes('--case3');
const outputPath = name => join(logs, case3 ? name.replace('routing-claude-', 'routing-claude-case3-') : name);
const root = resolve(logs, '../..');
const disposable = 'F:/AWWV-agent-setup-modernization-backup/20260912-8913cca6/claude-routing-project';
mkdirSync(disposable, { recursive: true });
const sources = ['AGENTS.md', 'CLAUDE.md', 'docs/20_engineering/AGENT_WORKFLOW.md', 'docs/20_engineering/CLAUDE_EXECUTION_STANDARD.md', '.claude/AGENT_TEAM_ROSTER.md', ...['using-superpowers','brainstorming','awwv-read-first','writing-plans','executing-plans','prompt-construction','awwv-make-cursor-prompt','verification-before-completion'].map(n=>`.claude/skills/${n}/SKILL.md`)];
const snapshot = sources.map(path => `SOURCE: ${path}\n${readFileSync(join(root,path),'utf8')}`).join('\n\n');
writeFileSync(outputPath('routing-claude-source-snapshot.txt'), snapshot);
writeFileSync(outputPath('routing-claude-source-hashes.json'), JSON.stringify(sources.map(path=>({path,sha256:createHash('sha256').update(readFileSync(join(root,path))).digest('hex')})),null,2)+'\n');
const args = ['--print','--tools','','--setting-sources','','--strict-mcp-config','--no-session-persistence','--model','sonnet','--effort','medium','--system-prompt-file',outputPath('routing-claude-source-snapshot.txt'),'--output-format','json'];
const child = spawn('C:/Users/User/.local/bin/claude.exe', args, { cwd: disposable, stdio:['pipe','pipe','pipe'], windowsHide:true });
let stdout='',stderr='',timedOut=false;
child.stdout.on('data', chunk=>stdout+=chunk);
child.stderr.on('data', chunk=>stderr+=chunk);
const allPrompts=readFileSync(join(logs,'routing-prompts.txt'),'utf8');
child.stdin.end(case3 ? allPrompts.split('\n')[0]+'\n\n'+allPrompts.split('\n').find(line=>line.startsWith('3.')) : allPrompts);
const timer = setTimeout(()=>{timedOut=true; child.kill();},90000);
child.on('error', error=>{stderr+=error.message;});
child.on('close', code=>{
  clearTimeout(timer);
  writeFileSync(outputPath('routing-claude-output.json'),stdout);
  writeFileSync(outputPath('routing-claude-stderr.log'),stderr);
  const receipt = {exit:code,timedOut,executable:'C:/Users/User/.local/bin/claude.exe',version:'2.1.269',requestedModel:'sonnet',effort:'medium',cwd:disposable,tools:[],settingSources:[],sessionPersistence:false,mode:case3?'targeted case 3 correction verification; original transcript retained':'one bounded read-only tabletop with four primary cases and two variants; candidate source snapshot supplied explicitly; no live activation or hook changes'};
  writeFileSync(outputPath('routing-claude-receipt.json'),JSON.stringify(receipt,null,2)+'\n');
  console.log(JSON.stringify(receipt));
  process.exitCode=code===0&&!timedOut?0:1;
});
