const fs = require('node:fs');
const cp = require('node:child_process');
const assert = require('node:assert/strict');
const git = (...args) => cp.execFileSync('git', args, {encoding:'utf8', maxBuffer:16*1024*1024}).trim();
const p2 = '558f253a2';
const rename = '1ddf6f01a';
const namePaths = ['data/source/oob_brigades.json', 'data/source/oob_brigade_designations.json', 'data/derived/startup/apr_1992_initial_save.json', 'src/ui/map/data/formationNameLocalizations.ts'];
const p2Paths = ['data/scenarios/events/war_1995.json','src/sim/events/evaluate_events.ts','src/sim/events/event_types.ts','src/sim/events/event_loader.ts','src/ui/map/utils/formatters.ts','src/ui/map/components/SettlementTimeline.tsx','src/ui/map/components/chronicle/ChronicleOverlay.tsx','src/ui/map/components/army_hq/DecisionConsequenceRecordsPanel.tsx'];
for (const file of namePaths) assert.equal(git('hash-object', '--path', file, file), git('rev-parse', `${rename}:${file}`), `Rename drift: ${file}`);
for (const file of p2Paths) assert.equal(git('hash-object', '--path', file, file), git('rev-parse', `${p2}:${file}`), `P2 drift: ${file}`);
const normalize = text => text.replace(/\r\n/g,'\n').trim();
const ledger = normalize(fs.readFileSync('docs/PROJECT_LEDGER.md','utf8'));
assert.ok(ledger.startsWith(normalize(git('show', `${p2}:docs/PROJECT_LEDGER.md`))), 'Main ledger history lost');
const branchLedger = normalize(git('show', `${rename}:docs/PROJECT_LEDGER.md`));
const marker = '## 2026-09-07 - R7 ARBiH brigade honorific display-name correction';
assert.ok(branchLedger.includes(marker));
assert.ok(ledger.includes(branchLedger.slice(branchLedger.indexOf(marker))), 'Branch ledger tail lost');
assert.equal(git('diff','--name-only','--diff-filter=U'),'','Unresolved conflicts');
console.log('PASS: all 12 production blobs match their reviewed source; both ledger histories preserved; no unresolved conflicts.');
